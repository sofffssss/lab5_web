// ------------------------------------------------------------
// Функція розрахунку кількості днів від поточної дати до дати концерту.
// Вхід:  text — дата у вигляді рядка "РРРР-ММ-ДД"
// Вихід: ціле число днів (додатне — концерт у майбутньому,
//        0 — сьогодні, від'ємне — концерт уже минув)
// ------------------------------------------------------------
function ras_Diff_Days(text) {
    // Поточна дата
    let currentDate = new Date();
    // Скидаємо час до 00:00:00, щоб рахувати саме дні
    currentDate.setHours(0, 0, 0, 0);

    // Перетворюємо рядок "РРРР-ММ-ДД" у Date
    let date1 = new Date(text + "T00:00:00");

    // Різниця в мілісекундах
    let timeDiff = date1.getTime() - currentDate.getTime();

    // Переводимо мілісекунди в дні
    let daysDiff = Math.round(timeDiff / (1000 * 3600 * 24));
    return daysDiff;
}

// ------------------------------------------------------------
// Функція формування рядка виводу для окремого запису масиву.
// Вхід:  item — поточний елемент масиву (об'єкт)
//        i    — номер поточного елементу
//        array — масив
// Вихід: дописує HTML-рядок у глобальну змінну html
// ------------------------------------------------------------
function vivod(item, i, array) {
    let text = item['Date'];
    let diffDays = ras_Diff_Days(text);

    // Визначаємо повідомлення та стиль рядка
    let message = "";
    let rowStyle = "";

    if (diffDays === 5) {
        // Сьогодні — останній термін придбання квитка (за 5 днів)
        message = "Сьогодні останній термін придбання квитка!";
        rowStyle = "background:yellow; color:#000;";
    } else if (diffDays === 0) {
        // Сьогодні йде концерт
        message = "Сьогодні йде концерт!";
        rowStyle = "background:red; color:#fff;";
    } else if (diffDays > 5) {
        message = "До концерту залишилось " + diffDays + " дн.";
    } else if (diffDays > 0 && diffDays < 5) {
        message = "Термін придбання квитка минув! До концерту " + diffDays + " дн.";
        rowStyle = "background:orange; color:#000;";
    } else {
        message = "Концерт уже відбувся (" + Math.abs(diffDays) + " дн. тому).";
        rowStyle = "background:#555; color:#fff;";
    }

    html = html + "<tr style='" + rowStyle + "'>";

    // Виводимо всі властивості об'єкта в окремі комірки
    for (let key in item) {
        let value = item[key];
        if (value === "") {
            value = "—";
        }
        html = html + "<td>" + value + "</td>";
    }
    html = html + "<td>" + message + "</td>";

    // Додаткове повідомлення, якщо місце не вказано
    if (item['Place'] === "") {
        html = html + "<td class='warn'>Невідома адреса проведення концерту</td>";
    } else {
        html = html + "<td>—</td>";
    }

    html = html + "</tr>";
}

